export function sentenceWorkshop(
  level: string,
  block: number,
  variant: number,
  portuguese: boolean,
): RoutineQuestion[] {
  const bank = (portuguese ? pt : en)[level];
  if (!bank) throw new Error('Sentence practice is unavailable at this study level.');
  const u = bank[(block + variant) % bank.length],
    other = bank[(block + variant + 1) % bank.length],
    p = portuguese;
  const base = {
    context: u.context,
    contextSpanish: u.contextES,
    why: u.whyES,
    explanationNative: u.why,
    category: u.category,
    hints: [{ native: u.hint, spanish: u.hintES }],
  };
  const id = `v3-${level.toLowerCase()}-${(block + variant) % bank.length}`;
  const q = (part: string, fields: Partial<RoutineQuestion>): RoutineQuestion => ({
    ...base,
    id: `${id}-${part}`,
    prompt: '',
    spanish: '',
    solution: '',
    choices: [],
    ...fields,
  });
  // Tiles are shuffled reproducibly. The stored edition/variant reproduces the exact task after reload.
  const tiles = [...u.tiles];
  let state = block * 31 + variant * 17 + 11;
  for (let i = tiles.length - 1; i > 0; i--) {
    state = (Math.imul(state, 1664525) + 1013904223) >>> 0;
    const j = state % (i + 1);
    [tiles[i], tiles[j]] = [tiles[j], tiles[i]];
  }
  const options = [u.answer, ...u.distractors];
  if (variant % 2 === 0) options.reverse();
  return [
    q('tiles', {
      format: 'tiles',
      prompt: p ? 'Monte uma frase para esta situação.' : 'Build a sentence for this situation.',
      spanish: 'Armá una oración para esta situación.',
      solution: u.sentence,
      solutionSpanish: u.sentenceES,
      choices: tiles,
      accepted: u.variants,
    }),
    q('gap', {
      format: 'gap',
      prompt: p ? 'Complete a lacuna por escrito.' : 'Type the missing form.',
      spanish: u.gapES,
      source: u.gap,
      solution: u.answer,
      solutionSpanish: u.sentenceES,
      choices: [],
      completedModel: u.sentence,
    }),
    q('transform', {
      format: 'transform',
      prompt: u.transform,
      spanish: u.transformES,
      source: u.sentence,
      solution: u.transformed,
      solutionSpanish: u.transformedES,
      accepted: u.transformVariants,
      choices: [],
    }),
    q('correct', {
      format: 'correct',
      prompt: p
        ? 'Corrija o erro sem mudar a situação.'
        : 'Correct the error without changing the situation.',
      spanish: 'Corregí el error sin cambiar la situación.',
      source: u.error,
      solution: u.corrected,
      solutionSpanish: u.correctedES,
      choices: [],
      incorrect: [u.error],
      accepted: u.variants,
    }),
    q('choice', {
      format: 'choice',
      prompt: p ? 'Confira a estrutura em contexto.' : 'Check the pattern in context.',
      spanish: 'Elegí la forma que completa el modelo. Es práctica de reconocimiento.',
      source: u.gap,
      solution: u.answer,
      solutionSpanish: u.sentenceES,
      completedModel: u.sentence,
      choices: options,
    }),
    q('new-context', {
      format: 'transform',
      prompt: other.transform,
      spanish: other.transformES,
      source: other.sentence,
      solution: other.transformed,
      solutionSpanish: other.transformedES,
      accepted: other.transformVariants,
      choices: [],
      context: other.context,
      contextSpanish: other.contextES,
      why: other.whyES,
      explanationNative: other.why,
      category: other.category,
      hints: [{ native: other.hint, spanish: other.hintES }],
    }),
  ];
}
